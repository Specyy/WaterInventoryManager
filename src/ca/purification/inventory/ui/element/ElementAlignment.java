package ca.purification.inventory.ui.element;

/**
 * The {@code ElementAlignment} enum represents the possible alignments for 
 * UI elements within a container or layout.
 *
 * <p>This enum defines three alignment options:</p>
 * <ul>
 *     <li>{@code LEFT} - Aligns the element to the left side.</li>
 *     <li>{@code CENTER} - Centers the element within the available space.</li>
 *     <li>{@code RIGHT} - Aligns the element to the right side.</li>
 * </ul>
 *
 * <p>Examples of use:
 * <pre>
 *     ElementAlignment alignment = ElementAlignment.CENTER;
 * </pre>
 * </p>
 * 
 * @see ElementStyle
 */
public enum ElementAlignment {
    LEFT,
    CENTER,
    RIGHT
}
